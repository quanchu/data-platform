// Run with node tests/test_demo_frontend.cjs. These are logic tests, not browser QA.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const directory = path.resolve(__dirname, '../src/data_platform/demo/static');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(directory, 'presentation.js'), 'utf8'), context);
const segments = (source, spans) => JSON.parse(JSON.stringify(context.sourceSegments(source, spans)));
const source = '😀 Hà Nội — Acme <script>alert(1)</script>';
let result = segments(source, [{start: 2, end: 8}]);
assert.equal(result.filter(part => part.highlighted).map(part => part.text).join(''), 'Hà Nội');
assert.equal(result.map(part => part.text).join(''), source);
result = segments(source, [{start: 0, end: 1}, {start: 0, end: 4}, {start: 3, end: 8}]);
assert.equal(result.map(part => part.text).join(''), source);
assert.equal(result.filter(part => part.highlighted).map(part => part.text).join(''), '😀 Hà Nội');
assert.equal(segments('abc', [{start: -10, end: 99}])[0].text, 'abc');
assert.deepEqual(segments('abc', [{start: 2, end: 1}, {start: undefined, end: 8}]), [{text: 'abc', highlighted: false}]);
new vm.Script(fs.readFileSync(path.join(directory, 'app.js'), 'utf8'));
console.log('Unicode, overlap, clipping, invalid spans, and frontend syntax checks passed.');
const progress = (task, events) => JSON.parse(JSON.stringify(context.workflowProgress(task, events)));
const repeated = Array.from({length: 100}, (_, sequence) => ({stage: 'selection', status: 'completed', sequence}));
let phases = progress('claimify', [{stage: 'run', status: 'running'}, ...repeated]);
assert.equal(phases.length, 6);
assert.equal(phases.find(phase => phase.id === 'selection').indices.length, 100);
assert.equal(phases.find(phase => phase.id === 'clarification').state, 'Waiting');
phases = progress('claimify', [...repeated, {stage: 'run', status: 'cancelled'}]);
assert.equal(phases.find(phase => phase.id === 'selection').state, 'Stopped');
assert.equal(phases.find(phase => phase.id === 'result').state, 'Stopped');
phases = progress('segmentation', [{stage:'gap_scores',status:'completed'}, {stage:'run',status:'completed'}]);
assert.equal(phases.find(phase => phase.id === 'boundaries').state, 'Complete');
assert.equal(phases.find(phase => phase.id === 'headings').state, 'Not used');
console.log('Logical-stage grouping and stop-state checks passed.');
